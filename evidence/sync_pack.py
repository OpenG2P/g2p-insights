#!/usr/bin/env python3
"""Sync this Evidence project's map assets from a country pack.

    python3 sync_pack.py --pack ../../../openg2p-data/packs/XKM

Why this exists
---------------
The boundary GeoJSON under static/geo/ used to be copied here by hand from
openg2p-data. Predictably it drifted: by the time this script was written the
copies were four commits behind the pack and were missing a fix for
self-intersecting simplified rings, so the map here and the map MDS serves were
different files claiming to be the same boundaries.

A pack is the single source of truth for geography. This copies from one, records
which one, and deletes assets belonging to a pack that is no longer selected —
that last part matters, because switching from Ethiopia to Kamuntu otherwise
leaves a stale woreda.geojson behind for the page to keep drawing.

What it writes
--------------
    static/geo/level<N>.geojson  one per level BELOW country, numbered by depth
    static/geo/pack.json         manifest plus level order, for the page to read
    pages/index.md               attribution and level labels, between their markers

Why the boundaries are numbered rather than named
-------------------------------------------------
The page used to fetch /geo/region.geojson, /geo/zone.geojson and
/geo/woreda.geojson. Those are Ethiopia's level names, so pointing the same page
at Kamuntu — which has region/district/ward/village — left it requesting two
files that do not exist, and the drill-down died below the first level. Depth is
the one thing every pack shares, so the files are numbered and the page never
names a level. The human-readable labels are generated into the page from the
pack instead.

Regenerating the attribution into the page rather than leaving it hardcoded is
the point of the exercise: COD-AB is CC BY-IGO and *must* be credited, Kamuntu is
fictitious and must not be presented as a real place, and neither statement
should depend on someone remembering to edit prose when the pack changes.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
GEO_DIR = os.path.join(HERE, "static", "geo")
PAGE = os.path.join(HERE, "pages", "index.md")
ATTR_START = "<!-- PACK-ATTRIBUTION:START — generated by sync_pack.py, do not edit -->"
ATTR_END = "<!-- PACK-ATTRIBUTION:END -->"
LVL_START = "<!-- PACK-LEVELS:START — generated by sync_pack.py, do not edit -->"
LVL_END = "<!-- PACK-LEVELS:END -->"


def attribution(manifest):
    """The note shown under the maps, built from the pack's own manifest."""
    name = manifest.get("country_name") or manifest.get("country")
    note = manifest.get("license_note", "")
    if manifest.get("synthetic"):
        # The manifest's own note already explains the invented boundaries and
        # codes, so only the headline and the data caveat are added here —
        # restating it produced the same sentence twice.
        body = (f"**{name} is a fictitious country, and these figures are "
                f"synthetic — they describe nobody.** {note}")
        status = "warning"
    else:
        body = (f"Boundaries: {manifest.get('source_title') or name} — "
                f"{manifest.get('source')}, {manifest.get('license')}. {note}")
        status = "info"
    return (f"{ATTR_START}\n<Alert status={status}>\n{body}\n\nFigures come from the NSR "
            f"reporting views and refresh when this page is rebuilt. Pack "
            f"`{manifest.get('country')}`, version {manifest.get('version')}.\n"
            f"</Alert>\n{ATTR_END}")


def level_labels(order):
    """Record which level each depth maps to, for whoever reads the page next.

    Written into the page rather than fetched at runtime so the site stays a
    static build with no request outstanding before the first map can draw, and
    so switching pack shows up as a reviewable diff instead of as different
    behaviour from the same source.
    """
    lines = [LVL_START, "<!--", "  Depth -> level name for the installed pack.",
             "  The page addresses levels by DEPTH; these are only the labels.", ""]
    for i, name in enumerate(order[1:], start=1):
        lines.append(f"    level{i}.geojson = {name}  (heading: {plural(name).title()})")
    lines += ["-->", LVL_END]
    return "\n".join(lines)


def plural(name):
    """Good enough for the level names packs actually use."""
    if name.endswith(("s", "x", "ch", "sh")):
        return name + "es"
    if name.endswith("y") and name[-2:-1] not in "aeiou":
        return name[:-1] + "ies"
    return name + "s"


def splice(page, start, end, block, append):
    """Replace the text between two markers, or append the block if absent."""
    if start in page and end in page:
        head, rest = page.split(start, 1)
        return head + block + rest.split(end, 1)[1]
    return (page.rstrip() + "\n\n" + block + "\n") if append else page


def retitle(page, order):
    """Rewrite this page's four section headings to the pack's own level names.

    Each heading line is replaced WHOLE, keyed on its leading number. Patching
    single words inside the line was tried first and produced "## 2 · Districts
    area" — the label landed where an adjective belonged, because prose does not
    have a reliable slot to substitute into.

    This knows the page has four numbered sections, which is fair: sync_pack.py
    is this page's build step, not a general-purpose templater.
    """
    below = order[1:]
    if len(below) < 3:
        return page
    l1, l2, l3 = below[0], below[1], below[2]
    # Headings 2 and 3 name the CLICKED area — "Selected region" alone told the
    # reader nothing about which region they were looking at.
    #
    # The name is read from the level's own query and guarded on its row count.
    # Two approaches failed first, both because the empty state is what is hard:
    #   {inputs.sel_lN.area_name}      renders the string "true" before any
    #                                  click — an unset input proxy is truthy
    #                                  and stringifies.
    #   <Value data={lN_head} .../>    renders a dashed "No Records" box, which
    #                                  looks like a broken widget in a heading.
    # The query row count is the honest signal: it is 0 until a selection filters
    # it, so the heading simply carries no name yet.
    headings = {
        1: f"## {plural(l1).title()}",
        2: f"## {l1.title()}{{#if l1_head.length}}: {{l1_head[0].area_name}}{{/if}}",
        3: f"## {l2.title()}{{#if l2_head.length}}: {{l2_head[0].area_name}}{{/if}}",
        4: f"## {plural(l3).title()} {{#if l2_head.length}}in {{l2_head[0].area_name}}{{/if}}— where to act",
    }
    # Anchored on a marker comment, not on the heading text. The headings used to
    # be numbered ("## 2 · ...") and the number was the anchor; without it the
    # lines are ambiguous to a regex, and anchoring on wording would break the
    # moment anyone rewords one.
    for n, text in headings.items():
        page = re.sub(rf"(?m)^<!-- HEADING:{n} -->\n## .*$",
                      f"<!-- HEADING:{n} -->\n" + text.replace("\\", "\\\\"), page)

    # The leaf level is named in several more places. "Area" was used as a
    # neutral placeholder and it reads as a distinct, lower tier — a reader
    # reasonably asks what an "area" is and why it is not a woreda.
    L3, L3s = l3.title(), plural(l3).title()
    page = re.sub(r'(?m)^### [A-Za-z ]+?(\{#if l3_head)', rf'### {l3.title()}\g<1>', page)
    page = re.sub(r'(?m)^### All .*$',
                  f'### All {plural(l3)} {{#if l2_head.length}}in '
                  f'{{l2_head[0].area_name}}{{/if}}', page)
    page = re.sub(r'<Column id=area_name title="[^"]*"', f'<Column id=area_name title="{L3}"', page)
    page = re.sub(r'title="Poverty score by [^"]*"', f'title="Poverty score by {l3} — highest first"', page)
    page = re.sub(r'every [a-z]+ in the selected [a-z]+', f'every {l3} in the selected {l2}', page)
    page = re.sub(r'when you click a single [a-z]+', f'when you click a single {l3}', page)
    return page


def _fetch(url, dest):
    """Download a boundary file, with credentials when the bucket needs them.

    The URL Master Data records points at object storage, which is NOT public: an
    anonymous GET returns 403. MDS wrote the object with the root credentials, so
    the same credentials are what read it back. They arrive as MAPS_S3_* and are
    optional — a deployment that fronts the bucket with a public read policy, or
    serves boundaries from a CDN, needs none of this and the plain fetch works.
    """
    import urllib.request

    key_id = os.environ.get("MAPS_S3_ACCESS_KEY")
    secret = os.environ.get("MAPS_S3_SECRET_KEY")
    if key_id and secret:
        try:
            import boto3
            from botocore.client import Config
            from urllib.parse import urlparse
            u = urlparse(url)
            endpoint = f"{u.scheme}://{u.netloc}"
            bucket, _, key = u.path.lstrip("/").partition("/")
            s3 = boto3.client("s3", endpoint_url=endpoint,
                              aws_access_key_id=key_id,
                              aws_secret_access_key=secret,
                              config=Config(signature_version="s3v4"))
            s3.download_file(bucket, key, dest)
            return
        except ImportError:
            print("[sync] boto3 not installed — trying an unauthenticated fetch")

    with urllib.request.urlopen(url, timeout=300) as r, open(dest, "wb") as fh:
        shutil.copyfileobj(r, fh)


def from_master_data(dsn):
    """Materialise a pack directory from Master Data, for RUN-time syncing.

    WHY THIS EXISTS
    ---------------
    Boundaries used to be baked into the image at BUILD time from a --pack
    directory, with COUNTRY_PACK as a build arg defaulting to XKM. The country a
    deployment actually carries is chosen at INSTALL time, in Master Data, so the
    two had no way of agreeing: a published image drew Kamuntu while the registry
    held Ethiopia, and because the choropleth joins on P-code the map came out
    EMPTY rather than wrong-looking — no error, nothing in a log.

    Master Data already knows the answer. It is seeded from the pack, uploads the
    simplified GeoJSON to object storage and records the URL on every geo row as
    boundary_simplified_uri. Nothing read it until now. Reading it here makes the
    map follow whatever pack the environment was seeded with, with no rebuild and
    no build argument.

    Returns a temporary directory shaped like a pack (levels.json, manifest.json,
    boundaries/<level>.geojson) so the rest of this script is unchanged.
    """
    import tempfile, urllib.request
    import psycopg2

    tmp = tempfile.mkdtemp(prefix="mds-pack-")
    bdir = os.path.join(tmp, "boundaries")
    os.makedirs(bdir, exist_ok=True)

    with psycopg2.connect(**dsn) as conn, conn.cursor() as cur:
        cur.execute("select level_id, level_mnemonic, parent_level_id "
                    "from g2p_geo_levels")
        rows = cur.fetchall()
        if not rows:
            raise SystemExit("[sync] Master Data holds no geo levels — seed the "
                             "country pack before building the maps.")
        # Order by walking parent -> child, not by level_id: the ids are opaque.
        by_parent = {}
        for lid, mnem, parent in rows:
            by_parent.setdefault(parent, []).append((lid, mnem))
        order, ids, cursor_ = [], [], None
        while by_parent.get(cursor_):
            lid, mnem = by_parent[cursor_][0]
            order.append(mnem); ids.append(lid); cursor_ = lid

        cur.execute("""select level_id, max(boundary_simplified_uri)
                       from g2p_geo_level_values
                       where boundary_simplified_uri is not null
                       group by level_id""")
        uri = dict(cur.fetchall())

        # Provenance from the ROOT unit. There is no `country` column on the geo
        # tables — the country IS the root unit, whose id is its P-code ("ET") and
        # whose display name is the country name.
        cur.execute("select level_value_id, coalesce(display_name, level_value_mnemonic), "
                    "pcode_source, version from g2p_geo_level_values "
                    "where level_id = %s", (ids[0] if ids else None,))
        root = cur.fetchone() or (None, None, None, None)
        country, country_name, source, version = root

    missing = [m for lid, m in zip(ids, order) if not uri.get(lid)]
    if missing:
        raise SystemExit(
            f"[sync] Master Data has no boundary URL for level(s) {missing}. "
            "Seed the pack with object storage configured "
            "(geoSeed.objectStore.endpoint on the master-data chart).")

    for lid, mnem in zip(ids, order):
        dest = os.path.join(bdir, f"{mnem}.geojson")
        print(f"[sync] fetching {mnem} <- {uri[lid]}")
        _fetch(uri[lid], dest)

    json.dump([{"level_id": l, "level_mnemonic": m,
                "parent_level_id": (ids[i-1] if i else None)}
               for i, (l, m) in enumerate(zip(ids, order))],
              open(os.path.join(tmp, "levels.json"), "w"))
    # `source` carries the upstream attribution (e.g. "OCHA COD-AB"), which the
    # page's licence block renders — losing it would drop a licence obligation.
    json.dump({"country": country or "?",
               "country_name": country_name,
               "synthetic": False,
               "version": version,
               "source": source or "Master Data Service",
               "levels": order},
              open(os.path.join(tmp, "manifest.json"), "w"))
    return tmp


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--pack", help="country pack directory (build-time source)")
    p.add_argument("--from-master-data", action="store_true",
                   help="take the boundaries from Master Data instead of a pack "
                        "directory — the country then follows whatever the "
                        "environment was seeded with, with no rebuild")
    p.add_argument("--dry-run", action="store_true")
    args = p.parse_args()

    if args.from_master_data:
        args.pack = from_master_data({
            "host": os.environ.get("MDS_PGHOST") or os.environ["PGHOST"],
            "port": os.environ.get("MDS_PGPORT", "5432"),
            "dbname": os.environ.get("MDS_DB", "master_data"),
            "user": os.environ.get("MDS_PGUSER") or os.environ["PGUSER"],
            "password": os.environ.get("MDS_PGPASSWORD") or os.environ.get("PGPASSWORD"),
        })
    elif not args.pack:
        p.error("one of --pack or --from-master-data is required")

    manifest = json.load(open(os.path.join(args.pack, "manifest.json")))
    levels = json.load(open(os.path.join(args.pack, "levels.json")))
    order = [lv["level_mnemonic"] for lv in levels]
    src = os.path.join(args.pack, "boundaries")

    # level0 is the country outline; the drill levels are 1..N.
    depth_name = {f"level{i}.geojson": m for i, m in enumerate(order)}
    wanted = set(depth_name) | {"pack.json"}
    stale = [f for f in (os.listdir(GEO_DIR) if os.path.isdir(GEO_DIR) else [])
             if f.endswith(".geojson") and f not in wanted]

    print(f"[sync] pack {manifest.get('country')} "
          f"({'synthetic' if manifest.get('synthetic') else 'real'}) "
          f"levels={order}")
    for f in stale:
        print(f"[sync] removing stale {f} (belongs to a different pack)")
    for fn, m in depth_name.items():
        print(f"[sync] {fn}  <- {m}")
    if args.dry_run:
        return

    os.makedirs(GEO_DIR, exist_ok=True)
    for f in stale:
        os.remove(os.path.join(GEO_DIR, f))
    for fn, m in depth_name.items():
        shutil.copyfile(os.path.join(src, f"{m}.geojson"),
                        os.path.join(GEO_DIR, fn))
    with open(os.path.join(GEO_DIR, "pack.json"), "w") as fh:
        json.dump({"levels": order, "manifest": manifest}, fh, indent=1)

    page = open(PAGE).read()
    page = splice(page, ATTR_START, ATTR_END, attribution(manifest), append=True)
    page = splice(page, LVL_START, LVL_END, level_labels(order), append=False)
    # Headings name the pack's own levels, so "Regions / Zones / Woredas" becomes
    # "Regions / Districts / Wards" without editing prose by hand.
    page = retitle(page, order)
    with open(PAGE, "w") as fh:
        fh.write(page)
    print(f"[sync] wrote attribution and level labels into "
          f"{os.path.relpath(PAGE, HERE)}")


if __name__ == "__main__":
    main()
